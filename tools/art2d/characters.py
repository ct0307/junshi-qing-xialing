def make_character(hero_id: str, size: int = 768) -> Image.Image:
    """返回透明 RGBA 原创二维全身稿；只支持 guan_yu 与 zhao_yun。

    以320逻辑坐标超采样绘制，台座视觉中心为(150,275)，768图对应(360,660)。
    不导出图片、不改正式资源、不调用网络；由根任务统一生成和目视评审。
    """
    if hero_id not in ("guan_yu", "zhao_yun"):
        raise ValueError("二维精修样例仅支持 guan_yu 与 zhao_yun")
    if not isinstance(size, int) or isinstance(size, bool) or size < 1:
        raise ValueError("图片尺寸必须是正整数")
    painter = _Painter(size)
    _base(painter)
    if hero_id == "guan_yu":
        _guan_weapon(painter)
        _guan_clothes(painter)
        _guan_arms(painter)
        _scaled_head(painter, _guan_head)
    else:
        _zhao_cape(painter)
        _zhao_weapon(painter)
        _zhao_body(painter)
        _zhao_arms(painter)
        _scaled_head(painter, _zhao_head)
    return painter.image.resize((size, size), Image.Resampling.LANCZOS)
