def _mask(p, commands):
    painter = _Painter(round(p.resolution / 3))
    painter.path(commands, "white")
    return painter.image.getchannel("A")


def _surface(p, commands, light, dark, outline=None, width=.7, horizontal=.3):
    """局部材质渐变始终裁在原创轮廓内，不能用整图滤镜代替重新造型。"""
    mask = _mask(p, commands)
    box = mask.getbbox()
    if box is None:
        return
    w, h = box[2] - box[0], box[3] - box[1]
    vertical = Image.linear_gradient("L").resize((w, h))
    across = Image.linear_gradient("L").rotate(90).resize((w, h))
    gradient = Image.blend(vertical, across, horizontal)
    material = ImageOps.colorize(gradient, light, dark).convert("RGBA")
    material.putalpha(mask.crop(box))
    p.image.alpha_composite(material, box[:2])
    p.draw = ImageDraw.Draw(p.image)
    if outline:
        p.path(commands, outline=_mix(outline, INK, .42), width=max(width * 1.6, 1.05))


def _glaze(p, commands, color, blur, opacity, clip):
    layer = _Painter(round(p.resolution / 3))
    layer.path(commands, color)
    image = layer.image.filter(ImageFilter.GaussianBlur(blur * p.scale))
    alpha = image.getchannel("A").point(lambda value: round(value * opacity))
    image.putalpha(ImageChops.multiply(alpha, _mask(p, clip)))
    p.image.alpha_composite(image)
    p.draw = ImageDraw.Draw(p.image)


def _scaled_head(p, draw_head):
    """两将共用轻微收束的头部比例，头盔与面部细节一起缩放。"""
    layer = _Painter(round(p.resolution / 3))
    draw_head(layer)
    center_x, center_y = 145 * p.scale, 94 * p.scale
    scale_x, scale_y = .97, .98
    transform = (1 / scale_x, 0, center_x * (1 - 1 / scale_x),
                 0, 1 / scale_y, center_y * (1 - 1 / scale_y))
    head = layer.image.transform(layer.image.size, Image.Transform.AFFINE, transform,
                                 resample=Image.Resampling.BICUBIC)
    p.image.alpha_composite(head)
    p.draw = ImageDraw.Draw(p.image)


