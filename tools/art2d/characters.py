def _cloud(p, x, y, scale, color, width=.65):
    # 小面积如意纹只用于金属中心或衣襟，不作密集铺纹。
    p.path([("M", x - 8 * scale, y + 2 * scale),
            ("C", x - 13 * scale, y, x - 9 * scale, y - 6 * scale, x - 4 * scale, y - 4 * scale),
            ("C", x - 3 * scale, y - 10 * scale, x + 5 * scale, y - 9 * scale, x + 5 * scale, y - 4 * scale),
            ("C", x + 11 * scale, y - 5 * scale, x + 13 * scale, y + scale, x + 7 * scale, y + 3 * scale),
            ("C", x + 4 * scale, y + 4 * scale, x + 3 * scale, y + scale, x + 6 * scale, y)],
           outline=color, width=width)


def _almond(p, left, top_a, top_b, right, low_a, low_b, iris_box, gaze, lid, iris):
    """杏眼用实画眼白、窄虹膜和细上睑；不使用圆眼球或对称大高光。"""
    points = (left, top_a, top_b, right, low_a, low_b)
    center_x = (min(point[0] for point in points) + max(point[0] for point in points)) / 2
    center_y = (min(point[1] for point in points) + max(point[1] for point in points)) / 2

    def scale_point(point):
        return (center_x + (point[0] - center_x) * .94,
                center_y + (point[1] - center_y) * .91)

    left, top_a, top_b, right, low_a, low_b = (scale_point(point) for point in points)
    iris_box = (center_x + (iris_box[0] - center_x) * .94,
                center_y + (iris_box[1] - center_y) * .91,
                center_x + (iris_box[2] - center_x) * .94,
                center_y + (iris_box[3] - center_y) * .91)
    gaze *= .94
    commands = [("M", *left), ("C", *top_a, *top_b, *right),
                ("C", *low_a, *low_b, *left)]
    p.path(commands, "#F8EAD7")
    # 在眼白内裁出虹膜，眼睑盖住其上缘，缩小后仍有明确视线。
    eye = _Painter(round(p.resolution / 3))
    eye.ellipse(iris_box, iris)
    ix = (iris_box[0] + iris_box[2]) / 2 + gaze
    eye.ellipse((ix - 1.15, iris_box[1] + .6, ix + 1.25, iris_box[3] - .3), "#243B35")
    eye.image.putalpha(ImageChops.multiply(eye.image.getchannel("A"), _mask(p, commands)))
    p.image.alpha_composite(eye.image)
    p.draw = ImageDraw.Draw(p.image)
    p.path([("M", *left), ("C", *top_a, *top_b, *right)], outline=lid, width=1)
    p.path([("M", *right), ("C", *low_a, *low_b, *left)], outline=_mix(lid, "#D3A78C", .6), width=.5)
    p.ellipse((ix - 1.0, iris_box[1] + 1.1, ix - .05, iris_box[1] + 2.0), "#FFF3DA")


def _hand(p, x, y, angle=0, bright="#EBC3A0", shade="#BB8164"):
    # 护胸手是收紧的小拳，掌根和指节以不同转折收束。
    dx, dy = angle * .4, angle * .2
    shape = [("M", x - 5, y - 5), ("C", x - 3, y - 7.3, x + .5, y - 7.3, x + 2.2, y - 5.5),
             ("L", x + 5.1 + dx, y - 2 + dy), ("L", x + 5.6, y + 1.8),
             ("C", x + 3, y + 5.7, x + .3, y + 6.8, x - 2.6, y + 5.1),
             ("L", x - 6.3, y + 1.8), ("L", x - 6.8, y - 1.6), ("L", x - 5, y - 5)]
    _surface(p, shape, bright, shade, _mix(shade, "#765943", .25), .65)
    p.path([("M", x - 4.6, y - 2.9), ("C", x - 2.4, y - 5, x + .4, y - 4.9, x + 1.1, y - 2.3),
            ("L", x - 1.1, y + .6)], outline=_mix(shade, "#735343", .35), width=.6)
    for index in range(2):
        p.curve((x - 1, y + 1.9 + index * 1.8), (x + 1, y + 2.8 + index * 1.7),
                (x + 3.2, y + 1.5 + index * 1.7), (x + 4, y + .5 + index * 1.7),
                _mix(shade, "#805D49", .25), .5)


def _grip(p, x, y, pole_slope, bright, shade, pole_light, pole_dark):
    # 先画杆后方的掌心，再露出一段杆，弯指与拇指最后跨在杆前。
    # 前后遮挡关系比掌心画纹更能说明侧握，不把整只手做成正面圆饼。
    edge = _mix(shade, "#7A5A44", .25)
    palm = [("M", x - 8.3, y - 4.8), ("L", x - 3.8, y - 7.5),
            ("C", x - .5, y - 7.6, x + 1.8, y - 5.7, x + 2.2, y - 2.8),
            ("L", x + 2.3, y + 4.7), ("L", x - 2.2, y + 7.2),
            ("C", x - 5, y + 7.6, x - 8.7, y + 3.1, x - 9.4, y + .7),
            ("L", x - 8.3, y - 4.8)]
    _surface(p, palm, bright, shade, edge, .6)
    p.polygon([(x - 2.1 - pole_slope * 8, y - 8),
               (x + 2.1 - pole_slope * 8, y - 8),
               (x + 2.1 + pole_slope * 8, y + 8),
               (x - 2.1 + pole_slope * 8, y + 8)], pole_dark)
    p.line([(x - .8 - pole_slope * 8, y - 8),
            (x - .8 + pole_slope * 8, y + 8)], pole_light, .7)
    for offset in (-4.4, -.5, 3.4):
        finger = [("M", x - 1.8, y + offset - 1.5),
                  ("C", x + .9, y + offset - 2.4, x + 4.3, y + offset - 1.7, x + 4.6, y + offset),
                  ("C", x + 4.6, y + offset + 2.1, x + 1.6, y + offset + 2.4, x - .6, y + offset + 1.5),
                  ("C", x - 1.9, y + offset + .8, x - 2.2, y + offset - .3, x - 1.8, y + offset - 1.5)]
        _surface(p, finger, _mix(bright, "#FFF1CF", .12), shade, edge, .45)
        p.curve((x + .2, y + offset - .9), (x + 1.6, y + offset - 1.4),
                (x + 3.1, y + offset - 1), (x + 3.5, y + offset - .1),
                _mix(bright, "#FFF0CA", .35), .4)
    thumb = [("M", x - 8.5, y - 1.3), ("C", x - 7.5, y - 4.1, x - 4.1, y - 6.3, x - 2.7, y - 5.3),
             ("L", x + .4, y - 1.8), ("C", x + 1.5, y - .3, x + .3, y + 1.4, x - 1.2, y + .9),
             ("L", x - 4.3, y - 1.4), ("C", x - 4.7, y + .6, x - 6.2, y + 2.5, x - 7.8, y + 2.5),
             ("L", x - 8.5, y - 1.3)]
    _surface(p, thumb, bright, shade, edge, .5)
    p.curve((x - 6.5, y - 2.3), (x - 5.4, y - 4.2), (x - 4, y - 4.7),
            (x - 3.2, y - 3.7), _mix(bright, "#FFF0CC", .35), .45)


